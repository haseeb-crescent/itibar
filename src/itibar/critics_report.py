GRADE = {0: "صحيح", 1: "حسن", 2: "ضعيف", 3: "شديد الضعف", 4: "متهم بالوضع", 5: "موضوع"}
DEF_SRC = lists.SOURCE_DIR / "critics_definitions.jsonl"


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        cells = []
        for v in r:
            if isinstance(v, (float, np.floating)):
                cells.append("" if pd.isna(v) else (f"{v:.1%}" if 0 <= v <= 1 and not float(v).is_integer()
                                                    else f"{v:,.0f}"))
            elif isinstance(v, (int, np.integer)) and not isinstance(v, bool):
                cells.append(f"{int(v):,}")
            else:
                cells.append("" if v is None else str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _pct(a, b) -> str:
    return f"{a / b:.1%}" if b else "—"


def definitions() -> dict[str, dict]:
    if not DEF_SRC.exists():
        return {}
    return {d["key"]: d for d in (json.loads(x) for x in open(DEF_SRC, encoding="utf-8"))}


def _load(name: str) -> pd.DataFrame:
    return pd.read_parquet(paths.OUT_DIR / "critics" / f"{name}.parquet")


def write() -> str:
    con = data.views()
    v = pd.read_parquet(verdicts.out_path())
    taf, gh, words = _load("tafarrud"), _load("gharib"), _load("words")
    shart, attr, wafi, pairs = _load("shart"), _load("attribution"), _load("wafi"), _load("pairs")
    nk = dict(con.sql("SELECT id, nickname FROM rawis").fetchall())
    bname = dict(con.sql("SELECT id, name FROM books").fetchall())
    L: list[str] = []
    w = L.append
    w("# The critics' verdicts: a test set from the texts\n")
    w("Generated by `make verdicts` (`itibar.verdicts`, `itibar.critics`) from `hadiths.nass` and the pipeline's "
      "outputs. Every claim is quoted from the hadith text it closes (`out/verdicts.parquet`: the span, a substring "
      "of `hadiths.nass`, gated); names are resolved among the narrators of that hadith's own chain(s); each claim "
      "is tested as it is stated — a relative claim as relative. **A failed claim is reported with what breaks it, "
      "never as the critic being wrong**: a route in a later book, a misresolved name and a route the critic judged "
      "unreliable are different findings and are kept apart.\n")
    # ---- 1. survey
    w("## 1. The survey: what the authors write after the matn\n")
    w("For every book whose author comments, the most frequent 3–5 token n-grams in the text after `matn_end` "
      "(`lists.normalize`; `reports/verdicts_survey.csv` keeps the top 30 per book for "
      f"{len(verdicts.SURVEY_BOOKS)} books). The parsers cover every family with more than a trivial count:\n")
    fam = pd.crosstab(v["family"], v["critic"])
    fam["total"] = fam.sum(axis=1)
    fam = fam.sort_values("total", ascending=False).reset_index()
    w(_md(fam))
    w("")
    w("**Families the brief did not name**, found by the survey: al-Bayhaqī's takhrīj attributions «رواه البخاري / "
      f"مسلم في الصحيح عن X» ({int((v['family'] == 'sahih_attribution').sum()):,}, §8); Abū Nuʿaym's «غريب من حديث X "
      "تفرد به Y», «لم نكتبه إلا من حديث X», «مشهور من حديث X», «صحيح متفق عليه / ثابت»; al-Khaṭīb relaying "
      "al-Ṭabarānī («قال سليمان لم يروه عن …», counted as al-Ṭabarānī's) and al-Haythamī's *Kashf al-Astār* relaying "
      "al-Bazzār («قال البزار لا نعلمه …», counted as al-Bazzār's), so one critic's claim is often read twice; "
      "al-Nasāʾī's «هذا خطأ» and «خالفه X» (the report as a disagreement between students); Ibn Khuzayma's «إن صح "
      "الخبر»; the chained exclusivity «لم يرو هذا الحديث عن X إلا Y ولا عنه إلا Z» (a single strand stated link by "
      "link); al-Ḥākim's «صحيح الإسناد ولم يخرجاه» (2,123: a verdict on the chain, not the shart). al-Dhahabī's "
      "Talkhīṣ is not in the text of `hadiths.nass` for al-Mustadrak (book 12): the baseline for al-Ḥākim is quoted "
      "from Shamela (§7). Not parsed (named in the survey, counts too small or not claims about the chain): Ibn "
      "Ḥibbān's «قال أبو حاتم» glosses (fiqh and wording), Abū Dāwūd's «رواه فلان» variants.\n")
    # ---- 2. samples
    w("## 2. Every claim type with its parse (samples)\n")
    for ct in v["claim_type"].value_counts().index:
        sm = v[v["claim_type"] == ct].sample(min(4, int((v["claim_type"] == ct).sum())), random_state=5)
        w(f"**{ct}** ({int((v['claim_type'] == ct).sum()):,})\n")
        for r in sm.itertuples(index=False):
            slots = {k: getattr(r, k) for k in ("grade", "scope", "clause", "x_text", "y_text", "z_text", "x_id", "y_id",
                                                 "z_id") if getattr(r, k) is not None and not (isinstance(getattr(r, k), float)
                                                                                               and pd.isna(getattr(r, k)))}
            if r.names is not None and len(r.names):
                slots["names"] = list(r.names)
            w(f"- hadith {r.hadith_id} ({r.critic}, {bname.get(r.book_id)}, p. {r.page_no}), `{r.family}`: «{r.span}» → "
              f"`{json.dumps(slots, ensure_ascii=False)}`")
        w("")
    # ---- 3. resolution
    w("## 3. Names resolved\n")
    rows = []
    for f in sorted(v["family"].unique()):
        x = v[v["family"] == f]
        for k in ("x", "y", "z"):
            t = x[x[f"{k}_text"].notna()]
            if not len(t):
                continue
            rs = t[f"{k}_reason"].fillna("").str.split(":").str[0]
            rows.append({"family": f, "slot": k, "slots": len(t), "resolved": int(t[f"{k}_id"].notna().sum()),
                         "share": t[f"{k}_id"].notna().mean(), "not in the chain": int((rs == "not_in_chain").sum()),
                         "ambiguous": int((rs == "ambiguous").sum()), "several names": int((rs == "several").sum())})
    w("Each name slot is resolved among the narrators of the hadith's own chain(s) by `conditional.find_names` (ism + "
      "father, «ابن» + father, kunya, nisba, a lone ism no other candidate bears; a span several fit resolves only to "
      "one carrying ≥ 95% of the links): «رسول الله», «النبي» are the PROPHET node. Unresolved slots are kept with the "
      "reason: *not in the chain* (the name is not one of the chain's narrators as the source resolved them — a "
      "different man, a namesake, or a narrator of another chain in the text), *ambiguous*, *several names*.\n")
    w(_md(pd.DataFrame(rows)))
    w("")
    # ---- 4. tafarrud
    w(_tafarrud(taf, nk, bname))
    # ---- 5. gharib, hasan
    w(_tirmidhi(gh, words, wafi, v))
    # ---- 6. wafi
    w(_wafi(wafi, pairs))
    # ---- 7. shart
    w(_shart(shart, nk))
    # ---- 8. attribution
    w(_attr(attr))
    # ---- 9. grade words
    w(_words(words))
    # ---- 10. definitions
    w(_defs())
    out = paths.REPORTS_DIR / "verdicts.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    fig7(taf, words)
    return str(out)


def _tafarrud(taf, nk, bname) -> str:
    L = ["## 4. Tafarrud: is the one the critic names a cut vertex of the routes through his teacher?\n"]
    L.append("Claims: al-Ṭabarānī's «لم يرو هذا الحديث عن X إلا Y» (X, Y as stated), «لا يروى عن X إلا بهذا الإسناد» "
             "(Y = X's student in the chain), «تفرد به Y» (X = Y's teacher in the chain), «ولا عنه إلا Z» (from the "
             "previous Y, only Z); al-Bazzār's «لا نعلم رواه عن X إلا Y», «لا نعلمه يروى عن X إلا من هذا الوجه» (Y = X's "
             "student; X absent = the Prophet, Y the companion); al-Tirmidhī's and al-Bazzār's «لا نعرفه / لا نعلمه إلا "
             "من حديث Y» and Abū Nuʿaym's «لم نكتبه إلا من حديث Y» (from the Prophet, only through Y); Abū Nuʿaym's «غريب "
             "من حديث X تفرد به Y». **Test:** in the group's bundle (on-path edges, threshold everyone), every route from "
             "X to a book passes through Y. *x/y not on path*: the resolved narrator is on no Prophet → book route of "
             "the bundle (a broken or mursal chain), so the claim cannot be tested there.\n")
    t = pd.crosstab(taf["critic_of_claim"], taf["status"])
    t["tested"] = t.get("holds", 0) + t.get("fails", 0)
    t["holds share of tested"] = t.get("holds", 0) / t["tested"].replace(0, np.nan)
    t["critic d."] = [CRITIC_DEATH.get(c) for c in t.index]
    t = t.sort_values("tested", ascending=False)
    L.append(_md(t.reset_index().rename(columns={"critic_of_claim": "critic"})))
    f = taf[taf["status"] == "fails"]
    L.append("\n**What breaks the failures.** For each failure the attested chains of the group through X that avoid Y "
             "are listed (`out/critics/tafarrud.parquet: breaking`). The failure is classed by its strongest breaking "
             "chain: *own book* (a chain in the critic's own works — al-Ṭabarānī's three Muʿjams and his other books, "
             "al-Bazzār's Musnad — goes through X without Y: the critic's statement is about the narrations he had "
             "*for this report*, and the meaning group can hold a different report of his), *earlier book* (a book "
             "whose compiler died before the critic: a route he could have known), *later book only* (every breaking "
             "chain is in a book compiled after him: a route he could not have known), *spliced route only* (no single "
             "chain breaks it; the union graph does).\n")
    k = pd.crosstab(f["critic_of_claim"], f["break_kind"])
    k["total"] = k.sum(axis=1)
    L.append(_md(k.sort_values("total", ascending=False).reset_index().rename(columns={"critic_of_claim": "critic"})))
    mis = f["all_misresolution_candidates"].fillna(False)
    cont = f["all_breaking_continuity_ok"].fillna(False)
    L.append(f"\nIn {int(mis.sum()):,} failures ({_pct(int(mis.sum()), len(f))}) every breaking chain is a "
             "**misresolution candidate** — the narrator below X in it is a namesake of Y (same ism and father, or the "
             "same name cluster), or its link to X is incompatible by the continuity rule: the data may have resolved "
             "the critic's own Y to another man, or attached the chain to the wrong X. These feed the gold-style error "
             f"rate (audit §10). In {int(cont.sum()):,} ({_pct(int(cont.sum()), len(f))}) every breaking chain passes "
             "the continuity rule.\n")
    # by book date relative to the critic
    rows = []
    for r in f.itertuples(index=False):
        for b in json.loads(r.breaking or "[]"):
            rows.append({"critic": r.critic_of_claim, "when": b.get("when") or "undated", "own": b.get("own_book")})
    bb = pd.DataFrame(rows)
    if len(bb):
        bt = pd.crosstab(bb["critic"], bb["when"])
        L.append("Breaking chains (all of them, up to 12 per failure) by their book's compiler's death year relative to "
                 "the critic's:\n")
        L.append(_md(bt.reset_index()))
    # printed failures
    L.append("\n**Printed failures** (a deterministic sample of 12; X → Y as resolved; each breaking chain with its "
             "book, the compiler's death year, the narrator below X, continuity and the namesake check):\n")
    for r in f.sample(min(12, len(f)), random_state=20261123).itertuples(index=False):
        X = "PROPHET" if r.X == "P" else f"{nk.get(int(r.X[1:]))} {r.X}"
        Y = f"{nk.get(int(r.Y[1:]))} {r.Y}" if r.Y and r.Y.startswith("r") else str(r.Y)
        L.append(f"- claim {r.claim_id}, {r.critic_of_claim} (d. {CRITIC_DEATH.get(r.critic_of_claim)}), hadith "
                 f"{r.hadith_id}, group {int(r.group_id)}: «{r.span}» — from {X}, only {Y}: **fails** ({r.break_kind}, "
                 f"{r.n_breaking} breaking chain(s))")
        for b in json.loads(r.breaking or "[]")[:3]:
            L.append(f"  - sanad {b['sanad_id']} in {bname.get(b['book_id'])} (book {b['book_id']}, compiler d. "
                     f"{b['book_death']}, {b['when']}{', own book' if b['own_book'] else ''}): below X "
                     f"{nk.get(b['below_x']) if b['below_x'] else '—'}; continuity "
                     f"{'ok' if b['continuity_ok'] else 'an incompatible link'}"
                     f"{'; namesake of Y' if b['namesake_of_y'] else ''}")
    L.append("")
    return "\n".join(L)


def _tirmidhi(gh, words, wafi, v) -> str:
    L = ["## 5. al-Tirmidhī: gharīb, ḥasan and the verdict classes\n"]
    a = gh[gh["absolute_holds"].notna()]
    L.append(f"**Gharīb, absolute.** Of {len(a):,} al-Tirmidhī claims of «غريب» (alone or in a combination) or «لا "
             f"نعرفه إلا من هذا الوجه» in a group with chains, the group's κ_all is 1 (gharīb by κ) in "
             f"{int(a['absolute_holds'].sum()):,} ({_pct(int(a['absolute_holds'].sum()), len(a))}).")
    rr = gh[gh["relative_holds"].notna()]
    L.append(f" **Relative** («غريب من هذا الوجه»: from the chain's companion only one student; «غريب من حديث X»: "
             f"from X only one): holds in {int(rr['relative_holds'].sum()):,} of {len(rr):,} testable "
             f"({_pct(int(rr['relative_holds'].sum()), len(rr))}). Most of al-Tirmidhī's gharīb reports reach the "
             "corpus through more than one route: the meaning group pools every book, later ones included, and the "
             "other companions' reports the source files as the same report (§6). §4 separates, for the cut test, "
             "the routes in books before and after the critic.\n")
    tw = words[words["family"] == "tirmidhi_verdict"].copy()
    tw["class"] = tw["grade"].map(lambda g: " ".join(x for x in ("حسن", "صحيح", "غريب") if x in set((g or "").split())))
    found = wafi.groupby("hadith_id")[["in_group", "in_siblings", "in_grandparent"]].any().any(axis=1)
    tw["wafi_found"] = tw["hadith_id"].map(found)
    tw["has_wafi"] = tw["hadith_id"].isin(set(v.loc[v["family"] == "wafi_al_bab", "hadith_id"]))
    rows = []
    for c, x in tw.groupby("class"):
        row = {"verdict": c, "claims": len(x)}
        for th in ("kappa_all", "kappa_above_matruk", "kappa_saduq_up", "kappa_thiqa_up"):
            k = x[th].dropna()
            row[f"{th} = 1"] = (k == 1).mean() if len(k) else None
            row[f"{th} median"] = float(k.median()) if len(k) else None
        row["«وفي الباب» given"] = x["has_wafi"].mean()
        row["… a named companion found"] = x["wafi_found"].fillna(False).mean()
        rows.append(row)
    L.append("**Each verdict class: what its bundles look like.** κ at each threshold for the group of the hadith "
             "the verdict closes; whether he gives a «وفي الباب» list and whether a named companion's chain is found "
             "(group, sibling or grandparent topic, §6). The «حسن غريب» puzzle — how a report his definition requires "
             "to be «يروى من غير وجه» can be gharīb — has been argued since Ibn al-Ṣalāḥ (§10); the table reports the "
             "bundles and does not resolve it.\n")
    L.append(_md(pd.DataFrame(rows)))
    rows = []
    for c, x in tw.groupby("class"):
        row = {"verdict": c, "claims": len(x)}
        lv = x["chain_level"].dropna()
        row["his chain's weakest level (median)"] = float(lv.median()) if len(lv) else None
        for col, lab in (("chain_template", "template"), ("chain_v1", "v1"), ("chain_v1_source", "v1 src map"),
                         ("chain_v2_ibn_hajar_classical", "v2 IH"), ("chain_v2_ibn_hajar_source", "v2 IH src"),
                         ("chain_v2_ibn_al_salah_classical", "v2 IS"), ("group_v2_ibn_hajar_classical", "group v2 IH"),
                         ("group_v2_ibn_hajar_source", "group v2 IH src"), ("group_recorded", "group recorded")):
            k = x[col].dropna()
            row[f"{lab}: 0 / 1 / 2+"] = (f"{(k == 0).mean():.0%} / {(k == 1).mean():.0%} / {(k >= 2).mean():.0%}"
                                         if len(k) else "")
        rows.append(row)
    L.append("\nThe codes beside each class (his own chain: the hadith's chain(s), lowest code; group: the report's "
             "bundle). IH = `ibn_hajar`, IS = `ibn_al_salah`; *src map* = the source's code map:\n")
    L.append(_md(pd.DataFrame(rows)))
    L.append("")
    return "\n".join(L)


def _wafi(wafi, pairs) -> str:
    L = ["## 6. «وفي الباب عن …»: the companions al-Tirmidhī names\n"]
    n = len(wafi)
    res = wafi["companion"].notna()
    cum_g = wafi["in_group"]
    cum_s = cum_g | wafi["in_siblings"]
    cum_w = cum_s | wafi["in_grandparent"]
    L.append(f"{int((wafi['claim_id'].nunique())):,} lists name {n:,} companions; {int(res.sum()):,} "
             f"({_pct(int(res.sum()), n)}) resolve to a companion who ends a chain within the widest scope (the "
             "grandparent topic node); the rest are not there or are ambiguous. **Recall by scope**, of all names "
             "(cumulative):\n")
    L.append(_md(pd.DataFrame([
        {"scope": "the same meaning group", "found": int(cum_g.sum()), "recall": cum_g.mean()},
        {"scope": "+ a sibling group (same lowest topic node, PR 5's search)", "found": int(cum_s.sum()), "recall": cum_s.mean()},
        {"scope": "+ under the same grandparent topic node", "found": int(cum_w.sum()), "recall": cum_w.mean()},
    ])))
    L.append("\nThe same group already holds the named companion's chain for most names: the source files much of what "
             "al-Tirmidhī calls «في الباب» as the same report. The «taraf» scope of the brief is read as the grandparent "
             "topic node: `tarafs` holds one row per meaning group, so «the same taraf» would be the group itself "
             "(DECISIONS D88).\n")
    if len(pairs):
        tp = pairs[pairs["named"]].groupby(["claim_id", "companion"])["dice"].max()
        npairs = pairs[~pairs["named"]].groupby(["claim_id", "companion"])["dice"].max()
        q = [0.1, 0.25, 0.5, 0.75, 0.9]
        rows = []
        for lab, s in (("true pairs (a named companion's best sibling matn)", tp),
                       ("non-pairs (an unnamed companion of the same siblings, best matn)", npairs)):
            row = {"set": lab, "pairs": len(s)}
            for x in q:
                row[f"q{int(x * 100)}"] = round(float(s.quantile(x)), 3) if len(s) else None
            row["≥ 0.32 (the floor)"] = (s >= 0.32).mean() if len(s) else None
            row["≥ 0.38 (strict)"] = (s >= 0.38).mean() if len(s) else None
            rows.append(row)
        L.append("**What the 0.32 floor is worth.** Over the sibling groups of the hadith, the idf-weighted Dice (PR 5, "
                 "`matn.Matns.overlap`) of al-Tirmidhī's matn against the best matn of each named companion (true "
                 "pairs) and of each other companion of the same siblings (non-pairs):\n")
        L.append(_md(pd.DataFrame(rows)))
        tp_rate = (tp >= 0.32).mean() if len(tp) else 0
        np_rate = (npairs >= 0.32).mean() if len(npairs) else 0
        n_tp, n_np = int((tp >= 0.32).sum()), int((npairs >= 0.32).sum())
        L.append(f"\nAt the floor the Dice keeps {tp_rate:.1%} of the true pairs and {np_rate:.1%} of the non-pairs: "
                 f"named companions score higher (median {tp.median():.3f} against {npairs.median():.3f}), but the floor "
                 f"finds few of al-Tirmidhī's shawāhid, and above it the named companions are {n_tp:,} of "
                 f"{n_tp + n_np:,} sibling candidates (the rest may be shawāhid he did not name, or other reports). His «في "
                 "الباب» names companions who narrated *on the subject*, often in other words; vocabulary overlap finds "
                 "the near-verbatim minority. This is the calibration set bucket 3 will use (`out/critics/pairs.parquet`), "
                 "and the measured reason sibling shawāhid stay a variant (D75, D94).\n")
    return "\n".join(L)


def _shart(shart, nk) -> str:
    d = definitions()
    L = ["## 7. al-Ḥākim's «على شرط الشيخين / مسلم / البخاري»\n"]
    L.append("For each claim, the men of al-Ḥākim's chain up to the Ṣaḥīḥayn's generation (pos 0, al-Ḥākim, and every "
             "narrator who died after 261 or, undated, sits after tabaka 11 are left out; companions are not judged): "
             "*men*: every one is a narrator of the named Ṣaḥīḥ (`rawis.is_bukhari`, `is_muslim`; for الشيخين both); "
             "*pairings*: every teacher → student link among them occurs in a chain of the named Ṣaḥīḥ (book 1, 2) "
             "anywhere in the corpus. `is_bukhari` does not separate the narrators al-Bukhārī cites only muʿallaq "
             "(reports/source_grade.md §2), so *men* is a lenient reading.\n")
    t = shart.groupby("clause").apply(lambda x: pd.Series({
        "claims": len(x), "men hold": int(x["men_ok"].fillna(False).sum()),
        "men and pairings hold": int((x["men_ok"].fillna(False) & x["pairs_ok"].fillna(False)).sum())}),
        include_groups=False).reset_index()
    t["men share"] = t["men hold"] / t["claims"]
    t["both share"] = t["men and pairings hold"] / t["claims"]
    L.append(_md(t))
    bad = Counter(x for xs in shart["men_not_in_sahih"].dropna() for x in json.loads(xs))
    L.append("\nThe narrators most often outside the named Ṣaḥīḥ: "
             + "; ".join(f"{nk.get(k)} r{k} ({c})" for k, c in bad.most_common(10)) + ".\n")
    ex = d.get("dhahabi_talkhis_example")
    if ex:
        L.append("**The classical baseline is al-Dhahabī's correction of al-Ḥākim.** The Talkhīṣ is not in the corpus "
                 f"text; one example from Shamela ({ex['book_title']}, {ex.get('page_label') or ''}, "
                 f"[{ex['book_id']}/{ex['page_id']}]({ex['url']}), hadith {ex.get('hadith_number')}): al-Ḥākim "
                 f"«{ex.get('hakim_verdict')}», al-Dhahabī «{ex.get('dhahabi_comment')}» — the same check as *men* "
                 "(a narrator Muslim did not rely on). A full comparison needs the Talkhīṣ digitized.\n")
    return "\n".join(L)


def _attr(attr) -> str:
    L = ["## 8. al-Bayhaqī's attributions to the Ṣaḥīḥayn\n"]
    vc = attr["attr_status"].value_counts()
    n = len(attr)
    L.append(f"«رواه البخاري / مسلم في الصحيح عن X» ({n:,} claims) says the Ṣaḥīḥ has the report through X, its "
             "compiler's teacher. Tested on the meaning group: a chain of that Ṣaḥīḥ in the same group whose pos-1 "
             "narrator (the compiler's teacher) is X, X resolved among those teachers.\n")
    L.append(_md(pd.DataFrame([{"status": k, "claims": int(c), "share": c / n} for k, c in vc.items()])))
    L.append("\n*no Ṣaḥīḥ chain in group*: the group holds no chain of the named Ṣaḥīḥ — the source filed the Ṣaḥīḥ's "
             "report in another meaning group (or the text holds several reports); *teacher not found*: the group has "
             "the Ṣaḥīḥ's chains but not through the teacher named, or the name is a kunya or a nisba the resolver "
             "does not read («عن أبي عاصم» for al-Ḍaḥḥāk b. Makhlad). Both are checks of the source's grouping as much "
             "as of the claim.\n")
    return "\n".join(L)


def _words(words) -> str:
    L = ["## 9. Grade words against the derived grades, critic by critic\n"]
    L.append("Each verdict claim against the codes of the critic's own chain (the hadith's chains, lowest code) and of "
             "the group: v1 and v2 under both rulesets and both code maps. Rows: the critic's word; cells: the share "
             "of claims at code 0 / 1 / ≥ 2.\n")
    ww = words.copy()
    ww["word"] = [g if isinstance(g, str) else None for g in ww["grade"]]
    ww.loc[ww["family"] == "hakim_shart", "word"] = "على شرط " + ww.loc[ww["family"] == "hakim_shart", "clause"].fillna("")
    cols = [("chain_template", "template"), ("chain_v1", "v1"), ("chain_v1_source", "v1 src"),
            ("chain_v2_ibn_hajar_classical", "v2 IH"), ("chain_v2_ibn_hajar_source", "v2 IH src"),
            ("chain_v2_ibn_al_salah_classical", "v2 IS"), ("chain_v2_ibn_al_salah_source", "v2 IS src"),
            ("group_v2_ibn_hajar_classical", "group v2 IH"), ("group_recorded", "group recorded")]
    for critic, x in ww.groupby("critic"):
        rows = []
        for word, y in x.groupby("word"):
            if len(y) < 5:
                continue
            row = {"word": word, "claims": len(y)}
            for c, lab in cols:
                k = y[c].dropna()
                row[lab] = f"{(k == 0).mean():.0%}/{(k == 1).mean():.0%}/{(k >= 2).mean():.0%}" if len(k) else ""
            rows.append(row)
        if rows:
            L.append(f"**{critic}**\n")
            L.append(_md(pd.DataFrame(rows).sort_values("claims", ascending=False)))
            L.append("")
    return "\n".join(L)


def _defs() -> str:
    d = definitions()
    if not d:
        return ""
    L = ["## 10. The classical definitions the claims are scored against\n",
         "Fetched from Shamela and matched byte for byte against the page text (`lists/source/critics_definitions.jsonl`, "
         "each with its page and URL); the README quotes them.\n"]
    for k, x in d.items():
        q = x["quote"].replace("\n", " ")
        L.append(f"- `{k}` — {x['book_title']}, {x.get('page_label') or ''} ([{x['book_id']}/{x['page_id']}]({x['url']})): "
                 f"«{q[:400]}{'…' if len(q) > 400 else ''}»")
    L.append("")
    return "\n".join(L)


def fig7(taf, words) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from itibar import figures as F
    tested = taf[taf["status"].isin(["holds", "fails"])].copy()
    tested["kind"] = np.where(tested["status"] == "holds", "holds", tested["break_kind"].fillna("fails"))
    order = ["holds", "own_book", "earlier_book", "later_book_only", "spliced_route_only"]
    t = pd.crosstab(tested["critic_of_claim"], tested["kind"]).reindex(columns=order, fill_value=0)
    t = t.loc[t.sum(axis=1).sort_values(ascending=False).index]
    t = t[t.sum(axis=1) >= 20]
    tw = words[words["family"] == "tirmidhi_verdict"].copy()
    tw["class"] = tw["grade"].map(lambda g: " ".join(x for x in ("حسن", "صحيح", "غريب") if x in set((g or "").split())))
    kb = pd.cut(tw["kappa_all"], [-1, 0, 1, 2, 9, 10 ** 6], labels=["0", "1", "2", "3–9", "≥10"])
    k = pd.crosstab(tw["class"], kb, normalize="index")
    csv = pd.concat([t.reset_index().rename(columns={"critic_of_claim": "row"}).assign(panel="tafarrud"),
                     k.reset_index().rename(columns={"class": "row"}).assign(panel="tirmidhi_kappa_all")])
    csv.to_csv(paths.FIGURES_DIR / "fig7_critics.csv", index=False)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2), gridspec_kw={"width_ratios": [1.2, 1]})
    colors = {"holds": F.BLUE[650], "own_book": F.BLUE[450], "earlier_book": F.BLUE[300], "later_book_only": F.BLUE[200],
              "spliced_route_only": F.BLUE[100]}
    labels = {"holds": "holds (a cut vertex)", "own_book": "fails: a route in his own works",
              "earlier_book": "fails: a route in an earlier book", "later_book_only": "fails: routes in later books only",
              "spliced_route_only": "fails: a spliced route only"}
    left = np.zeros(len(t))
    y = np.arange(len(t))
    for c in order:
        a1.barh(y, t[c].to_numpy(), left=left, color=colors[c], label=labels[c])
        left += t[c].to_numpy()
    a1.set_yticks(y)
    a1.set_yticklabels(list(t.index))
    a1.invert_yaxis()
    a1.set_xlabel("tafarrud claims tested")
    a1.set_title("Tafarrud: the named narrator a cut vertex of the routes through his teacher?", fontsize=9)
    a1.legend(frameon=False, fontsize=7, loc="lower right")
    a1.grid(axis="x", color=F.GRID, linewidth=0.6)
    a1.set_axisbelow(True)
    cls = [c for c in ["حسن صحيح", "حسن", "حسن غريب", "حسن صحيح غريب", "صحيح", "غريب", "صحيح غريب"] if c in k.index]
    k = k.reindex(cls)
    tr = {"حسن صحيح": "hasan sahih", "حسن": "hasan", "حسن غريب": "hasan gharib", "حسن صحيح غريب": "hasan sahih gharib",
          "صحيح": "sahih", "غريب": "gharib", "صحيح غريب": "sahih gharib"}
    left = np.zeros(len(k))
    shades = [F.BLUE[100], F.BLUE[650], F.BLUE[450], F.BLUE[300], F.BLUE[200]]
    for i, c in enumerate(k.columns):
        a2.barh(np.arange(len(k)), k[c].to_numpy(), left=left, color=shades[i % len(shades)], label=f"κ_all {c}")
        left += k[c].to_numpy()
    a2.set_yticks(np.arange(len(k)))
    a2.set_yticklabels([tr.get(c, c) for c in k.index])
    a2.invert_yaxis()
    a2.set_xlabel("share of verdicts")
    a2.set_title("al-Tirmidhī's verdict classes by κ_all of the report's bundle", fontsize=9)
    a2.legend(frameon=False, fontsize=7, loc="lower right")
    fig.tight_layout()
    for ext in ("png", "svg"):
        fig.savefig(paths.FIGURES_DIR / f"fig7_critics.{ext}", dpi=160)
    plt.close(fig)
