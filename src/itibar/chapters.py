"""`make chapters`: the chapter census. For every level-1 and level-2 node of the
source's topic tree (a nested set, `topics.lft/rgt`), over the distinct meaning
groups under it: how many; the share with kappa_all = 1; with kappa_thiqa_up <= 1;
the median kappa_all; the share by number_class; and the share whose v2 grade
differs from v1 (it depends on corroboration). Shares are over the groups with
chains; groups without chains are counted separately.
reports/chapters.md, figures/fig5_chapter_census.{png,svg,csv} (level 1 only)."""

from __future__ import annotations

import duckdb
import pandas as pd

from itibar import config, data, paths

CLASSES = ["gharib_mutlaq", "gharib_nisbi", "aziz", "mashhur", "mutawatir_count"]


def census(con=None) -> pd.DataFrame:
    con = con or data.views()
    rs = config.load("structure")["derive"]["ruleset"]
    topics = con.sql("SELECT id, name, level, lft, rgt, tree_id, group_id FROM topics").df()
    rec = pd.read_parquet(paths.records_path(), columns=[
        "group_id", "status", "kappa_all", "kappa_thiqa_up", "number_class", "derived_code", f"code_v2_{rs}",
        "v2_by_corroboration", "matn_no_group"])
    d = duckdb.connect()
    d.register("t", topics)
    d.register("r", rec)
    rows = d.sql(f"""
        WITH nodes AS (SELECT id, name, level, lft, rgt, tree_id FROM t WHERE level IN (1, 2)),
             leaf AS (SELECT lft, tree_id, group_id FROM t WHERE group_id IS NOT NULL),
             ng AS (SELECT DISTINCT nodes.id, leaf.group_id FROM nodes JOIN leaf
                    ON leaf.tree_id = nodes.tree_id AND leaf.lft BETWEEN nodes.lft AND nodes.rgt)
        SELECT nodes.id AS topic_id, nodes.name, nodes.level, nodes.lft,
               count(ng.group_id) AS groups,
               count(*) FILTER (WHERE r.status = 'ok') AS groups_with_chains,
               avg((r.kappa_all = 1)::INT) FILTER (WHERE r.status = 'ok') AS share_kappa_all_1,
               avg((r.kappa_thiqa_up <= 1)::INT) FILTER (WHERE r.status = 'ok') AS share_kappa_thiqa_le_1,
               median(r.kappa_all) FILTER (WHERE r.status = 'ok') AS median_kappa_all,
               {", ".join(f"avg((r.number_class = '{c}')::INT) FILTER (WHERE r.status = 'ok') AS share_{c}" for c in CLASSES)},
               avg((r.number_class IS NULL)::INT) FILTER (WHERE r.status = 'ok') AS share_no_class,
               avg((r.derived_code != r.code_v2_{rs})::INT) FILTER (WHERE r.status = 'ok') AS share_v2_differs,
               avg(r.v2_by_corroboration::INT) FILTER (WHERE r.status = 'ok') AS share_v2_by_corroboration
        FROM nodes LEFT JOIN ng ON ng.id = nodes.id LEFT JOIN r ON r.group_id = ng.group_id
        GROUP BY ALL ORDER BY nodes.lft""").df()
    return rows


def report(df: pd.DataFrame | None = None) -> str:
    df = df if df is not None else census()
    rs = config.load("structure")["derive"]["ruleset"]
    def pct(v) -> str:
        return "" if pd.isna(v) else f"{v:.0%}"
    L = ["# The chapter census", "",
         "Generated by `make chapters`. The source's topic tree (`topics`, a nested set of 54,862 nodes) is a",
         "table of contents of the law and the creed; this census groups the meaning groups under each level-1",
         "and level-2 node (a group listed under several nodes counts in each). Shares are over groups with",
         "chains. κ_all = 1: one route at most at every cut (a single strand somewhere); κ_thiqa+ ≤ 1: at most one",
         "route of thiqa-and-above narrators. Number class: width on Taqrīb layers 1–12 (README). v2 ≠ v1: the",
         f"derived grade changes once corroboration is applied (ruleset `{rs}`).", "",
         "## Level 1", "",
         "| chapter | groups (with chains) | κ_all = 1 | κ_thiqa+ ≤ 1 | median κ_all | gharīb muṭlaq | gharīb nisbī | ʿazīz | mashhūr | mutawātir (count) | v2 ≠ v1 |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]

    def line(r) -> str:
        return (f"| {r.name} ({r.topic_id}) | {int(r.groups):,} ({int(r.groups_with_chains):,}) | {pct(r.share_kappa_all_1)} | "
                f"{pct(r.share_kappa_thiqa_le_1)} | {'' if pd.isna(r.median_kappa_all) else f'{r.median_kappa_all:g}'} | "
                f"{pct(r.share_gharib_mutlaq)} | {pct(r.share_gharib_nisbi)} | {pct(r.share_aziz)} | {pct(r.share_mashhur)} | "
                f"{pct(r.share_mutawatir_count)} | {pct(r.share_v2_differs)} |")

    for r in df[df["level"] == 1].itertuples(index=False):
        L.append(line(r))
    L += ["", "## Level 2 (under each level-1 chapter, in tree order)", "",
          "| node | groups (with chains) | κ_all = 1 | κ_thiqa+ ≤ 1 | median κ_all | gharīb muṭlaq | gharīb nisbī | ʿazīz | mashhūr | mutawātir (count) | v2 ≠ v1 |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in df.itertuples(index=False):
        if r.level == 1:
            L.append(f"| **{r.name}** |  |  |  |  |  |  |  |  |  |  |")
        else:
            L.append(line(r))
    L.append("")
    text = "\n".join(L)
    (paths.REPORTS_DIR / "chapters.md").write_text(text, encoding="utf-8")
    df.to_csv(paths.FIGURES_DIR / "fig5_chapter_census.csv", index=False)
    _fig5(df[df["level"] == 1])
    return text


def _fig5(d1: pd.DataFrame) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from itibar import figures as F
    d1 = d1.sort_values("share_kappa_all_1")
    labels = {"gharib_mutlaq": "gharīb muṭlaq", "gharib_nisbi": "gharīb nisbī", "aziz": "ʿazīz",
              "mashhur": "mashhūr", "mutawatir_count": "mutawātir (count ≥ N)", "no_class": "no route"}
    cols = ["gharib_mutlaq", "gharib_nisbi", "aziz", "mashhur", "mutawatir_count", "no_class"]
    colors = [F.BLUE[700], F.BLUE[550], F.BLUE[400], F.BLUE[250], F.BLUE[150], F.GRID]
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11.5, 5.2), gridspec_kw={"width_ratios": [1.6, 1]}, sharey=True)
    y = range(len(d1))
    names = [f"{n} ({int(g):,})" for n, g in zip(d1["name"], d1["groups_with_chains"])]
    left = [0.0] * len(d1)
    for c, colr in zip(cols, colors):
        v = d1[f"share_{c}"].fillna(0).to_list()
        a1.barh(list(y), v, left=left, color=colr, edgecolor=F.SURFACE, linewidth=1.5, height=0.7, label=labels[c])
        left = [a + b for a, b in zip(left, v)]
    a1.set_yticks(list(y), names)
    a1.set_xlim(0, 1)
    a1.set_xlabel("share of groups, by number class")
    a1.legend(ncol=3, fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12))
    a1.set_title("Chapters of the topic tree: number class")
    for col, mk, colr, lab in (("share_kappa_all_1", "o", F.BLUE[700], "κ_all = 1"),
                               ("share_kappa_thiqa_le_1", "s", F.BLUE[400], "κ_thiqa+ ≤ 1"),
                               ("share_v2_differs", "D", F.INK2, "v2 grade ≠ v1")):
        a2.scatter(d1[col], list(y), marker=mk, s=36, color=colr, label=lab, zorder=3)
    a2.set_xlim(0, 1)
    a2.grid(True, axis="x", color=F.GRID, lw=0.6)
    a2.set_xlabel("share of groups")
    a2.legend(fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.12), ncol=3)
    a2.set_title("Single routes and corroboration")
    fig.text(0.01, 0.01, "Level-1 nodes of the source's topic tree; groups under several nodes count in each. "
             "Source: hadith-kg (CC-BY-4.0), itibar records.", fontsize=7, color=F.MUTED)
    fig.subplots_adjust(left=0.2, right=0.98, top=0.93, bottom=0.2, wspace=0.08)
    for ext in ("png", "svg"):
        fig.savefig(paths.FIGURES_DIR / f"fig5_chapter_census.{ext}", dpi=200)
    plt.close(fig)


def main() -> None:
    df = census()
    report(df)
    print(f"{len(df)} level-1/2 nodes -> {paths.REPORTS_DIR / 'chapters.md'}")


if __name__ == "__main__":
    main()
